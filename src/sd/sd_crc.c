/*
 * SD card CRCs (SD Physical Layer Simplified Specification, 4.5):
 *
 *   CRC7   x^7 + x^3 + 1           commands and responses (CMD line)
 *   CRC16  x^16 + x^12 + x^5 + 1   data, one per data line (CCITT, init 0)
 *
 * In 4-bit mode each of D0-D3 carries its own CRC16 over its own bits. Taken
 * as one bit stream -- each nibble MSB first, D3 D2 D1 D0, which is simply
 * the data bytes MSB first -- the four CRCs are ONE CRC with the polynomial
 * P(x^4) = x^64 + x^48 + x^20 + 1: P(x^4) has only powers of x^4, so the
 * remainder splits line by line, and its 64 bits ARE the four CRC16s
 * interleaved nibble-wise, in exactly the order they go out on the wire
 * (16 nibbles after the data). So one table-driven CRC64 does all four lines
 * a byte at a time. test/host/sd_crc_test.c checks it against four separate
 * bit-by-bit CRC16s.
 *
 * The tables are plain MSB-first CRC tables of those polynomials; the test
 * rebuilds every result bit by bit, so a wrong entry cannot pass.
 */
