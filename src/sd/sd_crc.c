uint8_t sd_crc7(const uint8_t *p, size_t n) {
    uint8_t c = 0;                 /* the CRC, kept shifted left by one */
    while (n--) { c = crc7_t[c ^ *p++]; }
    return c >> 1;
}

uint16_t sd_crc16(const uint8_t *p, size_t n) {
    uint16_t c = 0;
    while (n--) { c = (uint16_t)((c << 8) ^ crc16_t[(uint8_t)(c >> 8) ^ *p++]); }
    return c;
}

uint64_t sd_crc16x4(const uint8_t *p, size_t n) {
    uint64_t c = 0;
    while (n--) { c = (c << 8) ^ crc64_t[(uint8_t)(c >> 56) ^ *p++]; }
    return c;
}

uint16_t sd_crc16x4_line(uint64_t crc, int line) {
    uint16_t v = 0;
    for (int i = 15; i >= 0; i--) {          /* bit i of the line's CRC sits at 4*i + line */
        v = (uint16_t)((v << 1) | ((crc >> (4 * i + line)) & 1u));
    }
    return v;
}
