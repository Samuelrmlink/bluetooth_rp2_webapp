#!/usr/bin/env python3
"""third_party/ca_roots/*.pem -> src/net/ca_roots.h (DER as C arrays).

The HTTP client's trust store (src/net/httpc_tls.c). Each root is checked
against the SHA-256 fingerprint pinned below before it is embedded, so a
swapped or corrupted PEM fails the build-time check (and tools/run_tests.py,
which runs this with --check) instead of silently changing what the device
trusts.

  tools/gen_ca_roots.py           regenerate the header
  tools/gen_ca_roots.py --check   exit 1 if the header is stale or a PEM is wrong
"""
import base64, hashlib, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "third_party", "ca_roots")
OUT = os.path.join(ROOT, "src", "net", "ca_roots.h")

# name, file, SHA-256 of the DER, where it came from
ROOTS = [
    ("GTS Root R1", "gtsr1.pem", "d947432abde7b7fa90fc2e6b59101b1280e0e1c7e4e40fa3c6887fff57a7f4cf", "https://pki.goog/repo/certs/gtsr1.pem"),
    ("GTS Root R2", "gtsr2.pem", "8d25cd97229dbf70356bda4eb3cc734031e24cf00fafcfd32dc76eb5841c7ea8", "https://pki.goog/repo/certs/gtsr2.pem"),
    ("GTS Root R3", "gtsr3.pem", "34d8a73ee208d9bcdb0d956520934b4e40e69482596e8b6f73c8426b010a6f48", "https://pki.goog/repo/certs/gtsr3.pem"),
    ("GTS Root R4", "gtsr4.pem", "349dfa4058c5e263123b398ae795573c4e1313c83fe68f93556cd5e8031b3c7d", "https://pki.goog/repo/certs/gtsr4.pem"),
    ("GlobalSign Root CA (R1)", "gsr1.pem", "ebd41040e4bb3ec742c9e381d31ef2a41a48b6685c96e7cef3c1df6cd4331c99", "https://secure.globalsign.com/cacert/root-r1.crt"),
    ("ISRG Root X1", "isrgx1.pem", "96bcec06264976f37460779acf28c5a7cfe8a3c0aae11a8ffcee05c0bddf08c6", "system trust store (Mozilla), = https://letsencrypt.org/certs/isrgrootx1.pem"),
    ("ISRG Root X2", "isrgx2.pem", "69729b8e15a86efc177a57afb7171dfc64add28c2fca8cf1507e34453ccb1470", "system trust store (Mozilla), = https://letsencrypt.org/certs/isrg-root-x2.pem"),
]

def der_of(path):
    txt = open(path).read()
    m = re.search(r"-----BEGIN CERTIFICATE-----(.*?)-----END CERTIFICATE-----", txt, re.S)
    if not m:
        raise SystemExit(f"{path}: no certificate")
    return base64.b64decode("".join(m.group(1).split()))

def render():
    out = ["/* GENERATED by tools/gen_ca_roots.py from third_party/ca_roots/ -- do not edit.",
           " * The HTTP client's trust store: DER, checked against the pinned SHA-256",
           " * fingerprints in the generator. */",
           "#ifndef BTGW_CA_ROOTS_H", "#define BTGW_CA_ROOTS_H", "#include <stddef.h>", "#include <stdint.h>", ""]
    names = []
    for i, (name, fn, fp, src) in enumerate(ROOTS):
        der = der_of(os.path.join(SRC, fn))
        got = hashlib.sha256(der).hexdigest()
        if got != fp:
            raise SystemExit(f"{fn}: SHA-256 {got} is not the pinned {fp}")
        out.append(f"/* {name}, {len(der)} bytes, sha256 {fp}\n * from {src} */")
        out.append(f"static const uint8_t ca_root_{i}[] = {{")
        for k in range(0, len(der), 16):
            out.append("    " + ", ".join(f"0x{b:02x}" for b in der[k:k + 16]) + ",")
        out.append("};")
        names.append((name, i, len(der)))
    out.append("")
    out.append("typedef struct { const char *name; const uint8_t *der; size_t len; } ca_root_t;")
    out.append("static const ca_root_t ca_roots[] = {")
    for name, i, n in names:
        out.append(f'    {{ "{name}", ca_root_{i}, {n} }},')
    out.append("};")
    out.append("#define CA_ROOTS_N (sizeof ca_roots / sizeof ca_roots[0])")
    out.append("")
    out.append("#endif")
    return "\n".join(out) + "\n"

if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        if not os.path.exists(OUT) or open(OUT).read() != text:
            print("src/net/ca_roots.h is stale: run tools/gen_ca_roots.py")
            sys.exit(1)
        print(f"{len(ROOTS)} roots, fingerprints pinned")
        sys.exit(0)
    open(OUT, "w").write(text)
    print(f"wrote {OUT}: {len(ROOTS)} roots")
