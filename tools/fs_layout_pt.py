#!/usr/bin/env python3
"""Turn a picotool partition-table binary into fs_layout_pt.c.

The bytes are embedded unchanged. fs.layout_commit programs them, 0xFF-padded
to flash pages, and a modified byte would fail the table's own hash.
"""
import sys

MARK = bytes([0xD3, 0xDE, 0xFF, 0xFF])


def main():
    if len(sys.argv) != 3:
        sys.exit("usage: fs_layout_pt.py <table.bin> <out.c>")
    data = open(sys.argv[1], "rb").read()
    if not data or len(data) > 4096 or len(data) % 4:
        sys.exit("partition table is %d bytes; want 4..4096 and a multiple of 4" % len(data))
    if MARK not in data:
        sys.exit("partition table has no picobin marker")
    lines = [
        "/* Generated by tools/fs_layout_pt.py. Do not edit. */",
        "#include <stdint.h>",
        "",
        "const uint8_t fs_layout_pt[] = {",
    ]
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16]
        lines.append("    " + ", ".join("0x%02x" % b for b in chunk) + ",")
    lines.append("};")
    lines.append("const uint32_t fs_layout_pt_len = %d;" % len(data))
    lines.append("")
    open(sys.argv[2], "w").write("\n".join(lines))


if __name__ == "__main__":
    main()
