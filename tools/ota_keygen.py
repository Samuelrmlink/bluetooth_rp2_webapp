#!/usr/bin/env python3
"""Create the OTA signing key and emit the public half as src/ota/ota_pubkey.h.

The PRIVATE key is written to ~/.config/btgw/ota-signing.pem (mode 0600),
OUTSIDE the repository, and is never uploaded to the device. Losing it means
signing nothing further with it; recovery is SWD (tools/debug.sh), which
bypasses OTA verification by design. Back it up like a credential.

Only the public key is committed. To rotate: generate a new key, build an
image carrying the NEW public key, sign it with the OLD private key, OTA it,
then sign with the new key from there on.
"""
import hashlib, os, subprocess, sys, pathlib

KEY = pathlib.Path(os.environ.get("BTGW_OTA_KEY", os.path.expanduser("~/.config/btgw/ota-signing.pem")))
ROOT = pathlib.Path(__file__).resolve().parent.parent
HDR = ROOT / "src/ota/ota_pubkey.h"


def pubkey_raw(key):
    der = subprocess.check_output(["openssl", "ec", "-in", str(key), "-pubout", "-outform", "DER"],
                                  stderr=subprocess.DEVNULL)
    # SubjectPublicKeyInfo for P-256 ends with 0x04 || X(32) || Y(32)
    assert der[-65] == 0x04 and len(der) >= 65, "not an uncompressed P-256 point"
    return der[-64:]


def main():
    force = "--force" in sys.argv
    if KEY.exists() and not force:
        print(f"key exists: {KEY} (use --force to replace it -- old images can then not be re-signed)")
    else:
        KEY.parent.mkdir(parents=True, exist_ok=True)
        os.chmod(KEY.parent, 0o700)
        subprocess.check_call(["openssl", "ecparam", "-name", "prime256v1", "-genkey", "-noout", "-out", str(KEY)])
        os.chmod(KEY, 0o600)
        print(f"wrote {KEY}")
    raw = pubkey_raw(KEY)
    fp = hashlib.sha256(raw).hexdigest()
    rows = []
    for i in range(0, 64, 8):
        rows.append("    " + ", ".join(f"0x{b:02x}" for b in raw[i:i + 8]) + ",")
    HDR.write_text(
        "/* OTA signing PUBLIC key: P-256, uncompressed X||Y, as micro-ecc wants it.\n"
        " * Generated by tools/ota_keygen.py; the private half lives outside the\n"
        " * repository (~/.config/btgw/ota-signing.pem) and never on the device.\n"
        f" * SHA-256 of these 64 bytes: {fp}\n"
        " */\n#ifndef OTA_PUBKEY_H\n#define OTA_PUBKEY_H\n#include <stdint.h>\n"
        "static const uint8_t OTA_PUBKEY[64] = {\n" + "\n".join(rows) + "\n};\n#endif\n")
    print(f"wrote {HDR.relative_to(ROOT)}  fingerprint {fp[:16]}...")


if __name__ == "__main__":
    main()
