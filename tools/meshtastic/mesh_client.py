#!/usr/bin/env python3
"""
A minimal Meshtastic client for the PC, over Bluetooth LE: the "person on the
mesh" end of the gateway's Meshtastic remote control (bluetooth_rp2_webapp).

    mesh_client.py scan                         Meshtastic nodes in range
    mesh_client.py pair <addr> [--pin 123456]   pair with BlueZ (PIN entry)
    mesh_client.py run <addr|name> [--fifo PATH] [--log FILE] [--hops N]

`run` connects, prints our node and the LoRa settings, then stays connected:
every received text is printed (sender, PKI or not, hops, SNR) and every DM we
send is tracked until its routing ACK, classified as:

    delivered  ACK from the recipient itself (from == destination)
    implicit   ACK generated by OUR node on overhearing a relay (from == us):
               "someone relayed it" -- NOT proof of delivery
    nak        an error reason (NO_RESPONSE, MAX_RETRANSMIT, PKI_FAILED ...)
    other      an ACK from a third node (unexpected; logged)

Commands (typed, or written one per line into --fifo):
    dm <dest> <text>   send a text DM (dest: !hexid, decimal node num, or a short/long name)
    nodes              nodes the radio knows (id, name, hops, public key?, last heard)
    nodeinfo <dest>    send our NodeInfo (incl. public key) and ask for theirs (key exchange)
    info               our node, firmware, LoRa preset/region/hop limit
    hops <n>           hop limit for our sends (default 1: keep tests off the wider mesh)
    quit

Never connect to the gateway's own node (a Meshtastic node takes ONE BLE client;
the gateway must hold it): node names/addresses in DENY are refused unless --force.
Everything is also appended to --log as JSON lines (default mesh_client.log.jsonl).

Setup (once):  python3 -m venv tools/meshtastic/.venv && tools/meshtastic/.venv/bin/pip install -r tools/meshtastic/requirements.txt
"""
import argparse
import json
import os
import select
import subprocess
import sys
import threading
import time

DENY = ["9d88", "DC:54:75:E1:9D:89"]    # the gateway's node (Meshtastic_9d88)

LOG = None
LOCK = threading.Lock()


def log(kind, **kw):
    rec = {"t": round(time.time(), 3), "kind": kind, **kw}
    with LOCK:
        line = " ".join(f"{k}={v}" for k, v in kw.items())
        print(f"{time.strftime('%H:%M:%S')} {kind:9s} {line}", flush=True)
        if LOG:
            LOG.write(json.dumps(rec, default=str) + "\n")
            LOG.flush()


MESH_SVC = "6ba1b218-15a8-461f-9fa8-5dcae273eafd"


def patch_ble_scan():
    """meshtastic 2.7's BLEInterface.scan() asks BlueZ for a service-UUID discovery
    filter, which bleak 3 + this BlueZ reject ("No discovery started"), and connect()
    uses scan() to find the device. Scan unfiltered and filter here instead."""
    from bleak import BleakScanner
    from meshtastic.ble_interface import BLEInterface, BLEClient

    def scan():
        with BLEClient() as client:
            found = client.async_await(BleakScanner.discover(timeout=10, return_adv=True))
        return [d for d, adv in found.values() if MESH_SVC in [u.lower() for u in adv.service_uuids]]

    BLEInterface.scan = staticmethod(scan)

    # A node that is paired but not advertising (BlueZ still holds a link, or it
    # just stopped) is missed by the scan; BlueZ knows a paired address, so let
    # connect() go to it directly.
    orig_find = BLEInterface.find_device

    def find_device(self, address):
        try:
            return orig_find(self, address)
        except BLEInterface.BLEError:
            if address and len(address.split(":")) == 6:
                class Known:
                    pass
                k = Known()
                k.address, k.name = address, address
                return k
            raise

    BLEInterface.find_device = find_device


def bluez_release(addr):
    """If the PC's BlueZ still holds a link to the node (e.g. left by pairing),
    drop it, so the node advertises and our own connection can take it."""
    if len(addr.split(":")) != 6:
        return
    info = subprocess.run(["bluetoothctl", "info", addr], capture_output=True, text=True).stdout
    if "Connected: yes" in info:
        subprocess.run(["bluetoothctl", "disconnect", addr], capture_output=True, text=True, timeout=15)
        time.sleep(2)
        log("released", addr=addr, note="BlueZ held a link; disconnected it first")


def denied(target):
    t = target.lower()
    return any(d.lower() in t for d in DENY)


# --- scan / pair -----------------------------------------------------------------

def cmd_scan(_args):
    patch_ble_scan()
    from meshtastic.ble_interface import BLEInterface
    devs = BLEInterface.scan()
    if not devs:
        print("no Meshtastic nodes found (is Bluetooth on in the node, and no phone connected to it?)")
    for d in devs:
        mark = "   <- the GATEWAY's node: do not connect" if denied(f"{d.name} {d.address}") else ""
        print(f"{d.address}  {d.name}{mark}")


def cmd_pair(args):
    """Pair through bluetoothctl's agent, answering the passkey prompt with --pin."""
    if denied(args.addr) and not args.force:
        sys.exit("refusing: that is the gateway's node (use --force if you really mean it)")
    p = subprocess.Popen(["bluetoothctl"], stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                         stderr=subprocess.STDOUT, text=True, bufsize=1)

    def send(s):
        p.stdin.write(s + "\n")
        p.stdin.flush()

    send("agent KeyboardOnly")
    send("default-agent")
    send("scan on")
    time.sleep(6)
    send("scan off")
    send(f"pair {args.addr}")
    deadline = time.time() + 40
    ok = False
    while time.time() < deadline:
        r, _, _ = select.select([p.stdout], [], [], 1)
        if not r:
            continue
        line = p.stdout.readline()
        if not line:
            break
        sys.stdout.write(line)
        low = line.lower()
        if "passkey" in low or "pin code" in low:
            send(args.pin)
        if "pairing successful" in low or "already paired" in low:
            ok = True
            break
        if "failed to pair" in low:
            break
    if ok:
        send(f"trust {args.addr}")
        send(f"disconnect {args.addr}")    # pairing leaves BlueZ connected; free the node
        time.sleep(2)
    send("quit")
    p.wait(timeout=5)
    print("PAIRED" if ok else "pairing did not succeed")
    sys.exit(0 if ok else 1)


# --- run ---------------------------------------------------------------------------

class Client:
    def __init__(self, iface, hops):
        self.iface = iface
        self.hops = hops
        self.pending = {}            # packet id -> {dest, sent, text}
        self.me = iface.localNode.nodeNum

    def resolve(self, dest):
        """!hexid, decimal, or a node's short/long name -> node num."""
        if dest.startswith("!"):
            return int(dest[1:], 16)
        if dest.isdigit():
            return int(dest)
        want = dest.lower()
        for n in (self.iface.nodes or {}).values():
            u = n.get("user", {})
            if want in (str(u.get("shortName", "")).lower(), str(u.get("longName", "")).lower(),
                        str(u.get("id", "")).lower()) or want in str(u.get("id", "")).lower():
                return n["num"]
        raise ValueError(f"unknown node {dest!r} (try 'nodes')")

    def name(self, num):
        n = (self.iface.nodesByNum or {}).get(num, {})
        u = n.get("user", {})
        return u.get("shortName") or u.get("longName") or f"!{num:08x}"

    # outgoing
    def dm(self, dest, text):
        from meshtastic.protobuf import portnums_pb2
        num = self.resolve(dest)
        sent = time.time()

        def on_response(p):
            self.on_ack(p)

        pkt = self.iface.sendData(text.encode(), destinationId=num,
                                  portNum=portnums_pb2.PortNum.TEXT_MESSAGE_APP,
                                  wantAck=True, onResponse=on_response,
                                  onResponseAckPermitted=True, hopLimit=self.hops)
        self.pending[pkt.id] = {"dest": num, "sent": sent, "text": text}
        log("sent", id=pkt.id, to=f"!{num:08x}", name=self.name(num), hops=self.hops,
            bytes=len(text.encode()), text=text)

    def nodeinfo(self, dest):
        """Send our User (with our public key) asking for theirs: how two nodes
        exchange keys without waiting for the periodic NodeInfo broadcast."""
        from google.protobuf import json_format
        from meshtastic.protobuf import mesh_pb2, portnums_pb2
        num = self.resolve(dest)
        u = dict(self.iface.getMyNodeInfo().get("user", {}))
        user = json_format.ParseDict(u, mesh_pb2.User(), ignore_unknown_fields=True)
        pkt = self.iface.sendData(user.SerializeToString(), destinationId=num,
                                  portNum=portnums_pb2.PortNum.NODEINFO_APP, wantResponse=True,
                                  wantAck=False, hopLimit=self.hops)
        log("nodeinfo", id=pkt.id, to=f"!{num:08x}", hops=self.hops)

    def on_ack(self, p):
        d = p.get("decoded", {})
        rid = d.get("requestId")
        reason = d.get("routing", {}).get("errorReason", "NONE")
        frm = int(p.get("from", 0))
        rec = self.pending.get(rid)
        if not rec:
            log("ack?", request_id=rid, frm=f"!{frm:08x}", reason=reason)
            return
        dt = round(time.time() - rec["sent"], 2)
        if reason != "NONE":
            kind = "nak"
        elif frm == rec["dest"]:
            kind = "delivered"
        elif frm == self.me:
            kind = "implicit"
        else:
            kind = "other"
        log(kind, id=rid, to=f"!{rec['dest']:08x}", frm=f"!{frm:08x}", reason=reason, after_s=dt)
        if kind in ("delivered", "nak"):
            self.pending.pop(rid, None)

    # incoming
    def on_receive(self, packet, interface=None):
        d = packet.get("decoded", {})
        port = d.get("portnum")
        frm = int(packet.get("from", 0))
        to = int(packet.get("to", 0))
        common = dict(frm=f"!{frm:08x}", name=self.name(frm), to=f"!{to:08x}",
                      pki=bool(packet.get("pkiEncrypted", False)),
                      hops=(packet.get("hopStart", 0) or 0) - (packet.get("hopLimit", 0) or 0),
                      snr=packet.get("rxSnr"), rssi=packet.get("rxRssi"))
        if port == "TEXT_MESSAGE_APP":
            log("text", **common, text=d.get("text", ""))
        elif port == "ROUTING_APP":
            pass                                    # handled by on_ack via the response handler
        elif port == "NODEINFO_APP":
            u = d.get("user", {})
            log("nodeinfo<", **common, id=u.get("id"), long=u.get("longName"), short=u.get("shortName"),
                pubkey="yes" if u.get("publicKey") else "no")
        elif port in ("TELEMETRY_APP", "POSITION_APP") and frm != self.me:
            log(port.split("_")[0].lower(), **common)

    def nodes(self):
        for n in sorted((self.iface.nodes or {}).values(), key=lambda n: -(n.get("lastHeard") or 0)):
            u = n.get("user", {})
            age = int(time.time() - n["lastHeard"]) if n.get("lastHeard") else None
            print(f"  {u.get('id', '?'):10s} {str(u.get('shortName', '')):5s} {str(u.get('longName', ''))[:24]:24s} "
                  f"hops={n.get('hopsAway', '?')} pubkey={'yes' if u.get('publicKey') else 'no'} "
                  f"last={age if age is not None else '-'}s")

    def info(self):
        mi = self.iface.myInfo
        meta = getattr(self.iface, "metadata", None)
        lora = self.iface.localNode.localConfig.lora
        log("info", me=f"!{self.me:08x}", name=self.name(self.me),
            fw=getattr(meta, "firmware_version", "?"), region=lora.region, preset=lora.modem_preset,
            use_preset=lora.use_preset, hop_limit=lora.hop_limit, our_hops=self.hops,
            reboots=getattr(mi, "reboot_count", "?"))

    def command(self, line):
        parts = line.strip().split(maxsplit=2)
        if not parts:
            return True
        c = parts[0].lower()
        try:
            if c == "dm" and len(parts) == 3:
                self.dm(parts[1], parts[2])
            elif c == "nodes":
                self.nodes()
            elif c == "nodeinfo" and len(parts) >= 2:
                self.nodeinfo(parts[1])
            elif c == "info":
                self.info()
            elif c == "hops" and len(parts) >= 2:
                self.hops = int(parts[1])
                log("hops", our_hops=self.hops)
            elif c in ("quit", "exit"):
                return False
            else:
                print("commands: dm <dest> <text> | nodes | info | hops <n> | quit")
        except Exception as e:                      # keep the session alive on a bad command
            log("error", cmd=line.strip(), error=e)
        return True


def cmd_run(args):
    global LOG
    if denied(args.target) and not args.force:
        sys.exit("refusing: that is the gateway's node -- it can only have one BLE client")
    LOG = open(args.log, "a")
    from pubsub import pub
    patch_ble_scan()
    from meshtastic.ble_interface import BLEInterface
    bluez_release(args.target)
    log("connect", target=args.target)
    iface = BLEInterface(args.target, noNodes=False)
    cl = Client(iface, args.hops)
    pub.subscribe(cl.on_receive, "meshtastic.receive")
    pub.subscribe(lambda interface=None: log("lost", target=args.target), "meshtastic.connection.lost")
    cl.info()

    sources = [sys.stdin]
    fifo = None
    if args.fifo:
        if not os.path.exists(args.fifo):
            os.mkfifo(args.fifo)
        # O_RDWR: we hold a writer ourselves, so the pipe never reports EOF between
        # writers (a command written while it was being reopened was lost)
        fifo = os.open(args.fifo, os.O_RDWR | os.O_NONBLOCK)
        sources = [fifo] + ([sys.stdin] if sys.stdin.isatty() else [])
        log("fifo", path=args.fifo)
    buf = b""
    try:
        running = True
        while running:
            r, _, _ = select.select(sources, [], [], 1)
            for s in r:
                if s is sys.stdin:
                    line = sys.stdin.readline()
                    if not line:
                        sources.remove(sys.stdin)
                        continue
                    running = cl.command(line) and running
                else:
                    try:
                        chunk = os.read(fifo, 4096)
                    except BlockingIOError:
                        continue
                    buf += chunk
                    while b"\n" in buf:
                        line, buf = buf.split(b"\n", 1)
                        running = cl.command(line.decode(errors="replace")) and running
    except KeyboardInterrupt:
        pass
    finally:
        log("close", pending=len(cl.pending))
        iface.close()


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("scan")
    p = sub.add_parser("pair")
    p.add_argument("addr")
    p.add_argument("--pin", default="123456")
    p.add_argument("--force", action="store_true")
    r = sub.add_parser("run")
    r.add_argument("target", help="BLE address or advertised name of the PC's node")
    r.add_argument("--fifo", help="also read commands from this named pipe")
    r.add_argument("--log", default="mesh_client.log.jsonl")
    r.add_argument("--hops", type=int, default=1, help="hop limit for our DMs (default 1)")
    r.add_argument("--force", action="store_true")
    args = ap.parse_args()
    {"scan": cmd_scan, "pair": cmd_pair, "run": cmd_run}[args.cmd](args)


if __name__ == "__main__":
    main()
