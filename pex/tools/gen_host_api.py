#!/usr/bin/env python3
"""host_api.json -> everything that must agree on the PEX host API.

  gen_host_api.py header  <host_api.json> <out pex_api.h>
  gen_host_api.py table   <host_api.json> <group> <out pex_host_<group>.c>
  gen_host_api.py stubs   <host_api.json> <m33|m0p> <reloc|pic> <out .S>
  gen_host_api.py check   <host_api.json>          # collisions, duplicates

One source (spec section 11): the module SDK header, the import veneers a
module links against and the on-device lookup tables are all generated from
host_api.json, so the three cannot drift apart. Symbols are identified by
FNV-1a 32 of the exported name (spec section 7).
"""
import json, os, re, sys


def fnv1a(s):
    h = 0x811C9DC5
    for b in s.encode():
        h ^= b
        h = (h * 0x01000193) & 0xFFFFFFFF
    return h


def load(path):
    api = json.load(open(path))
    seen, hashes, ids = set(), {}, set()
    for g in api["groups"]:
        if g["id"] in ids:
            sys.exit(f"host_api: duplicate group id {g['id']}")
        ids.add(g["id"])
        for f in g.get("functions", []):
            n = f["name"]
            if n in seen:
                sys.exit(f"host_api: {n} defined twice")
            seen.add(n)
            h = fnv1a(n)
            if h in hashes:
                sys.exit(f"host_api: FNV-1a collision {n} / {hashes[h]} (0x{h:08x}): rename one")
            hashes[h] = n
            f.setdefault("since", 0)
            f.setdefault("impl", n)
            f.setdefault("decl", True)
            if f["since"] > g["minor"]:
                sys.exit(f"host_api: {n} since {f['since']} > group {g['name']} minor {g['minor']}")
    return api


def write(path, text):
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    old = open(path).read() if os.path.exists(path) else None
    if old != text:                      # keep timestamps stable for make/ninja
        open(path, "w").write(text)


def header(api):
    o = ["/* GENERATED by pex/tools/gen_host_api.py from pex/host_api.json -- do not edit. */",
         "#ifndef PEX_API_H", "#define PEX_API_H", "",
         f"#define PEX_API_MAJOR {api['api']['major']}",
         f"#define PEX_API_MINOR {api['api']['minor']}", ""]
    for g in api["groups"]:
        G = g["name"].upper()
        o.append(f"/* ---- group '{g['name']}' (id {g['id']}, v{g['major']}.{g['minor']}): {g.get('doc', '')} */")
        o.append(f"#define PEX_GROUP_{G} {g['id']}u")
        o.append(f"#define PEX_GROUP_{G}_MAJOR {g['major']}")
        o.append(f"#define PEX_GROUP_{G}_MINOR {g['minor']}")
        o += g.get("types", [])
        for f in g.get("functions", []):
            if f["decl"]:
                doc = f"  /* {f['doc']} */" if f.get("doc") else ""
                o.append(f"{f['proto']};{doc}")
        o.append("")
    o.append("#endif")
    return "\n".join(o) + "\n"


def table(api, gname):
    g = next((x for x in api["groups"] if x["name"] == gname), None)
    if g is None:
        sys.exit(f"no group {gname}")
    fns = sorted(g.get("functions", []), key=lambda f: fnv1a(f["name"]))
    o = ["/* GENERATED by pex/tools/gen_host_api.py from pex/host_api.json -- do not edit. */",
         '#include "pex_rt.h"', ""]
    impls = {}
    for f in fns:
        if f["impl"] != f["name"] and f["impl"] not in impls:
            impls[f["impl"]] = f["proto"].replace(f["name"] + "(", f["impl"] + "(", 1)
    for p in impls.values():
        o.append(p + ";")
    o.append(f"static const pex_hsym_t tbl[] = {{")
    for f in fns:
        o.append(f"    {{ 0x{fnv1a(f['name']):08x}u, (const void *)&{f['impl']} }},  /* {f['name']} */")
    o.append("};")
    o.append(f"const pex_group_t pex_group_{gname} = {{ {g['id']}, {g['major']}, {g['minor']}, "
             f"{len(fns)}, tbl, \"{gname}\" }};")
    return "\n".join(o) + "\n"


STUB = {
    ("m33", "reloc"): ["ldr r12, 1f", "ldr pc, [r12]", ".balign 4", "1: .word {got}"],
    ("m33", "pic"): ["ldr r12, 1f", "add r12, r9", "ldr pc, [r12]", ".balign 4", "1: .word {got}(sbrel)"],
    ("m0p", "reloc"): ["push {{r0, r1}}", "ldr r0, 1f", "ldr r0, [r0]", "str r0, [sp, #4]", "pop {{r0, pc}}",
                       ".balign 4", "1: .word {got}"],
    ("m0p", "pic"): ["push {{r0, r1}}", "ldr r0, 1f", "add r0, r9", "ldr r0, [r0]", "str r0, [sp, #4]",
                     "pop {{r0, pc}}", ".balign 4", "1: .word {got}(sbrel)"],
}
CPU = {"m33": "cortex-m33", "m0p": "cortex-m0plus"}


def stubs(api, target, model):
    body = STUB[(target, model)]
    o = ["/* GENERATED by pex/tools/gen_host_api.py -- import veneers + GOT slots,",
         f" * target {target}, model {model}. One section per symbol: --gc-sections",
         " * keeps only what the module calls; pexlink finds the kept slots by their",
         " * __pex_got_<name> symbols and lists them in IMPORTS. The loader fills them. */",
         ".syntax unified", ".thumb", ""]
    for g in api["groups"]:
        for f in g.get("functions", []):
            n, got = f["name"], "__pex_got_" + f["name"]
            o += [f".section .text.pex_imp.{n},\"ax\",%progbits", ".balign 4", f".global {n}",
                  f".type {n}, %function", ".thumb_func", f"{n}:"]
            o += ["    " + line.format(got=got) for line in body]
            o += [f".size {n}, . - {n}",
                  f".section .pex.got.{n},\"aw\",%progbits", ".balign 4", f".global {got}",
                  f".hidden {got}", f".type {got}, %object", f"{got}: .word 0", f".size {got}, 4", ""]
    return "\n".join(o) + "\n"


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    cmd, api = sys.argv[1], load(sys.argv[2])
    if cmd == "header":
        write(sys.argv[3], header(api))
    elif cmd == "table":
        write(sys.argv[4], table(api, sys.argv[3]))
    elif cmd == "stubs":
        write(sys.argv[5], stubs(api, sys.argv[3], sys.argv[4]))
    elif cmd == "check":
        n = sum(len(g.get("functions", [])) for g in api["groups"])
        print(f"host_api: api {api['api']['major']}.{api['api']['minor']}, "
              f"{len(api['groups'])} groups, {n} symbols, no collisions")
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
